"""Build evaluation/REPORT.md from evaluation/results/. Scores are never typed by hand."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"
EXPLANATIONS = {
    "hit_rate_at_k_pct": "An expected source appears in the retrieved passages",
    "primary_source_found_pct": "The most important expected source was retrieved",
    "mean_reciprocal_rank": "How high the first expected source ranks (1.0 is always first)",
    "mean_precision_at_k_pct": "Share of retrieved passages from an expected source",
    "median_latency_ms": "Median retrieval time",
    "out_of_scope_with_no_evidence_pct": "Out-of-scope questions stopped by the threshold alone",
    "questions": "Questions run",
    "claims": "Claims run",
    "llm_errors": "Provider failures during the run",
    "overall_pass_pct": "Questions passing all their checks",
    "answer_rate_on_answerable_pct": "Answerable questions that got an answer",
    "accuracy_expected_facts_pct_of_answerable": "Contains expected facts (of all answerable)",
    "accuracy_expected_facts_pct_of_answered": "Contains expected facts (of those answered)",
    "citation_urls_valid_pct": "Citations whose URL matches the source list",
    "cited_expected_document_pct_of_answered": "Answered, and cited an expected document",
    "faithfulness_proxy_mean": "Mean sentence-to-passage similarity (a proxy, not proof)",
    "correct_abstention_pct": "Out-of-scope questions correctly not answered",
    "correct_decline_pct": "Partisan or prediction requests declined",
    "latency_s_median": "Median response time (seconds)",
    "latency_s_p95": "95th percentile response time (seconds)",
    "correct_assessment_pct": "Claims given the expected category",
    "unverifiable_claims_given_a_verdict": "Unverifiable claims wrongly given a verdict",
    "responses_with_accusatory_language": "Responses with accusatory language",
}


def table(summary: dict) -> list[str]:
    lines = ["| Measure | Result |", "|---|---|"]
    for key, value in summary.items():
        if isinstance(value, (dict, list)):
            continue
        lines.append(f"| {EXPLANATIONS.get(key, key)} | {'n/a' if value is None else value} |")
    return lines


def main() -> None:
    out = ["# CivicBridge AI: evaluation report", "",
           "Generated by `evaluation/make_report.py` from the files in `evaluation/results/`. Do not edit by hand.", ""]
    for path in sorted(RESULTS.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        if "summary" not in data:
            continue
        run = data["run"]
        out += [f"## {path.stem}", "",
                f"Run {run['timestamp']}, model `{run['llm_provider']}/{run['llm_model'] or 'none'}`, "
                f"embeddings `{run['embedding_backend']}`, top-k {run['top_k']}, threshold {run['similarity_threshold']}.", ""]
        out += table(data["summary"]) + [""]
        for code, values in data["summary"].get("by_language", {}).items():
            out += [f"Language `{code}`:", ""] + table(values) + [""]
        if data["summary"].get("human_meaning_review"):
            out += [f"**Human meaning review:** {data['summary']['human_meaning_review']}", ""]
        failures = [q for q in data.get("questions", data.get("claims", [])) if q.get("passed") is False]
        if failures:
            out += ["Did not pass: " + ", ".join(f"`{q['id']}`" for q in failures), ""]
    ui = RESULTS / "ui_results.json"
    if ui.exists():
        checks = json.loads(ui.read_text())
        out += ["## Browser checks", "", f"{sum(c['passed'] for c in checks)} of {len(checks)} passed "
                "(Chrome at 360px and 1280px, axe WCAG 2 A/AA and best-practice rules, keyboard order, error states). "
                "Citation and verification display checks use an intercepted response, because they test rendering, not truth.", ""]
    (ROOT / "REPORT.md").write_text("\n".join(out), encoding="utf-8")
    print("Wrote evaluation/REPORT.md")


if __name__ == "__main__":
    main()
